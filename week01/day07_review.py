# ============================================================
# 数据：一个班级的学生成绩
# ============================================================
students = [
    {"name": "小明", "scores": [88, 92, 79]},
    {"name": "小红", "scores": [95, 88, 100]},
    {"name": "小刚", "scores": [60, 72, 55]},
    {"name": "小美", "scores": [78, 85, 90]},
]


# ============================================================
# 任务 1：计算每个学生的平均分
# ============================================================
def average(scores: list) -> float:
    """返回分数列表的平均值，保留 1 位小数。"""
    return round(sum(scores) / len(scores), 1)


print("=== 每人平均分 ===")
for s in students:
    avg = average(s["scores"])
    print(f"{s['name']}: {avg}")


# ============================================================
# 任务 2：找出平均分最高的学生
# ============================================================
top_student = max(students, key=lambda s: average(s["scores"]))
print(f"\n=== 第一名: {top_student['name']} ===")


# ============================================================
# 任务 3：用推导式列出所有「平均分及格(>=60)」的学生名字
# ============================================================
passed = [s["name"] for s in students if average(s["scores"]) >= 60]
print(f"\n=== 及格名单: {passed} ===")


# ============================================================
# 任务 4：生成 {名字: 平均分} 的字典（字典推导式）
# ============================================================
report = {s["name"]: average(s["scores"]) for s in students}
print(f"\n=== 成绩单字典 ===\n{report}")


# ============================================================
# 任务 5：统计全班每科的平均分
# ============================================================
subjects = ["语文", "数学", "英语"]
print("\n=== 各科平均分 ===")
for i, subject in enumerate(subjects):
    # 取出所有学生第 i 科的成绩
    subject_scores = [s["scores"][i] for s in students]
    print(f"{subject}: {average(subject_scores)}")


