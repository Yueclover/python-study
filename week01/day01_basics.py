# ============================================================
# 1. 变量与类型 —— 不用 let/const，直接赋值
# ============================================================
name = "前端转 AI 的你"        # str，对应 JS 的 string
age = 28                       # int，整数
height = 1.75                  # float，浮点数
is_learning = True             # bool，注意首字母大写！
nothing = None                 # 对应 JS 的 null/undefined

# type() 查看类型，print() 输出
print(type(name), type(age), type(is_learning))

# 👉 试一试：把 age 改成 "28"（带引号），再看 type 的变化
age = "28"
print(type(age))


# ============================================================
# 2. 字符串 —— f-string 就是 JS 的模板字符串
# ============================================================
greeting = f"你好，{name}！你今年 {age} 岁。"   # 对应 `你好 ${name}`
print(greeting)

# 常用字符串方法（和 JS 很像）
print("Hello".upper())          # HELLO
print("  trim 我  ".strip())    # 去空格，对应 JS 的 trim()
print("a,b,c".split(","))       # ['a', 'b', 'c']
print("-".join(["2026", "06", "11"]))  # 2026-06-11

# 👉 试一试：用 f-string 拼一句包含 height 的话并打印
print(f"你{height:.2f}米高")


# ============================================================
# 3. 数字运算 —— 多了 // 和 **
# ============================================================
print(10 / 3)    # 3.333... 普通除法
print(10 // 3)   # 3   整除（JS 要 Math.floor）
print(10 % 3)    # 1   取余
print(2 ** 10)   # 1024 幂运算（JS 是 2 ** 10 也行，但没有 //）


# ============================================================
# 4. 输入 —— input() 永远返回字符串
# ============================================================
