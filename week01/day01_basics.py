# ============================================================
# 5. 一个小练习：BMI 计算器
# ============================================================
def calc_bmi(weight_kg: float, height_m: float) -> float:
    """计算 BMI。type hints (: float) 你写过 TS 会很熟悉。"""
    return weight_kg / (height_m ** 2)


bmi = calc_bmi(70, height)
print(f"BMI = {bmi:.1f}")   # :.1f 保留 1 位小数

if bmi < 18.5:
    print("偏瘦")
elif bmi < 24:
    print("正常")
else:
    print("偏重")

